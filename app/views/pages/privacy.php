<h1>Protección de datos</h1>

<div class="card" style="border:1px solid var(--border); border-radius:var(--radius); padding:24px; background:#fff;">
  <p>En KAMAQ protegemos los datos personales que nos entregas, de acuerdo a la legislación chilena vigente sobre protección de la vida privada (Ley N° 19.628 y normativa aplicable).</p>

  <ul>
    <li>Tus datos se utilizan únicamente para procesar tu pedido y coordinar el envío.</li>
    <li>No compartimos ni vendemos tu información personal a terceros.</li>
    <li>Tus datos de pago se manejan a través de la pasarela de pago, sin almacenarse en nuestros servidores.</li>
    <li>Puedes solicitar la corrección o eliminación de tus datos en cualquier momento escribiéndonos.</li>
  </ul>
</div>
